-- Выполни весь SQL в Supabase → SQL Editor → New query → Run.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  display_name text,
  created_at timestamptz not null default now()
);

-- Автоматически создаём профиль при регистрации, даже если включено подтверждение почты.
create or replace function public.near_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, username, display_name)
  values (
    new.id,
    lower(coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email, '@', 1))),
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists near_on_auth_user_created on auth.users;
create trigger near_on_auth_user_created
after insert on auth.users
for each row execute procedure public.near_handle_new_user();

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text,
  image_path text,
  created_at timestamptz not null default now(),
  constraint message_has_content check (
    (body is not null and length(trim(body)) > 0) or image_path is not null
  )
);
create index if not exists messages_pair_created_idx
on public.messages(sender_id, recipient_id, created_at);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;

create policy "Profiles can be read by signed-in users"
on public.profiles for select to authenticated using (true);
create policy "Users can create own profile"
on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "Users can update own profile"
on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create policy "Participants can read messages"
on public.messages for select to authenticated
using (auth.uid() = sender_id or auth.uid() = recipient_id);
create policy "Users can send messages as themselves"
on public.messages for insert to authenticated
with check (auth.uid() = sender_id and sender_id <> recipient_id);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('near-media','near-media',false,8388608,array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public=false, file_size_limit=8388608,
allowed_mime_types=array['image/jpeg','image/png','image/webp','image/gif'];

create policy "Users upload to own folder"
on storage.objects for insert to authenticated
with check (bucket_id='near-media' and (storage.foldername(name))[1]=auth.uid()::text);

create policy "Chat participants can view attached images"
on storage.objects for select to authenticated
using (
 bucket_id='near-media' and (
   (storage.foldername(name))[1]=auth.uid()::text
   or exists (
     select 1 from public.messages m
     where m.image_path = name
       and (m.sender_id=auth.uid() or m.recipient_id=auth.uid())
   )
 )
);
